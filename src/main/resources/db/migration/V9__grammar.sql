-- =============================================================================
-- Grammar (spec: .kiro/specs/grammar/design.md §7)
-- Lessons are documents: queried fields as columns, the body as jsonb.
-- Learner state: progress (+ finished lessons), runs, review cards.
-- =============================================================================

create table grammar_lesson (
    id           bigint generated by default as identity primary key,  -- ids are taken from the sequence by the app
    slug         varchar(80)  not null unique,
    level        varchar(2)   not null check (level in ('A2', 'B1', 'B2', 'C1')),
    topic_key    varchar(60)  not null,
    title        text         not null,                                -- English title, for lists
    position     int          check (position >= 1),                   -- place in the level's course
    status       varchar(16)  not null default 'DRAFT' check (status in ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    revision     int          not null default 1 check (revision >= 1),
    version      bigint       not null default 0,
    content      jsonb        not null,                                -- the body (lesson-format.md), with answer keys
    published_at timestamptz,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now()
);
create unique index grammar_lesson_position_uq on grammar_lesson (level, position) where status = 'PUBLISHED';
create index grammar_lesson_course_idx on grammar_lesson (level, topic_key) where status = 'PUBLISHED';

create table grammar_progress (
    user_id    bigint primary key references app_user (id) on delete cascade,
    level      varchar(2) check (level in ('A2', 'B1', 'B2', 'C1')),     -- null = not chosen yet
    updated_at timestamptz not null default now()
);

create table grammar_finished_lesson (
    user_id           bigint     not null references grammar_progress (user_id) on delete cascade,
    lesson_id         bigint     not null references grammar_lesson (id) on delete restrict,
    level             varchar(2) not null check (level in ('A2', 'B1', 'B2', 'C1')),
    first_finished_on date       not null,                              -- a day in the grammar day zone
    times_finished    int        not null default 1 check (times_finished >= 1),
    primary key (user_id, lesson_id)
);
create index grammar_finished_day_idx on grammar_finished_lesson (user_id, level, first_finished_on);

create table grammar_run (
    id              uuid        primary key,
    lesson_id       bigint      not null references grammar_lesson (id) on delete restrict,
    lesson_revision int         not null check (lesson_revision >= 1),
    user_id         bigint      references app_user (id) on delete cascade,   -- null = guest
    started_at      timestamptz not null,
    finished_at     timestamptz,
    mastered        jsonb       not null default '[]',                         -- check item ids
    retries         int         not null default 0 check (retries >= 0),
    answered        int         not null default 0 check (answered >= 0)
);
create index grammar_run_cleanup_idx on grammar_run (started_at) where finished_at is null;
create index grammar_run_lesson_idx on grammar_run (lesson_id);

create table grammar_review_card (
    id               uuid        primary key,
    user_id          bigint      not null references app_user (id) on delete cascade,
    lesson_id        bigint      not null references grammar_lesson (id) on delete restrict,
    item_id          varchar(8)  not null,
    box              smallint    not null check (box between 1 and 4),
    due_on           date        not null,
    last_answered_on date,
    created_at       timestamptz not null default now(),
    constraint grammar_review_card_item_uq unique (user_id, lesson_id, item_id)
);
create index grammar_review_due_idx on grammar_review_card (user_id, due_on);
create index grammar_review_lesson_idx on grammar_review_card (lesson_id);
