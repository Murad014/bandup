-- =============================================================================
-- Vocabulary (spec: .kiro/specs/vocabulary/design.md §7)
-- One shared word card per base form (content as jsonb), each spelling owned by
-- exactly one card (vocab_word_form), learners' saved words, sessions, and the
-- daily count of AI cards per learner.
-- =============================================================================

create table vocab_word (
    id           bigint generated by default as identity primary key,  -- ids are taken from the sequence by the app
    lemma        varchar(40),                                          -- null while the AI writes it
    status       varchar(16)  not null check (status in ('PREPARING', 'READY', 'FAILED', 'REJECTED')),
    source       varchar(8)   not null default 'AI' check (source in ('AI', 'ADMIN')),
    revision     int          not null default 0 check (revision >= 0),
    attempts     int          not null default 0 check (attempts >= 0),
    last_error   text,
    content      jsonb,                                                -- card-format.md; null until READY
    version      bigint       not null default 0,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now(),
    check (status <> 'READY' or (lemma is not null and content is not null))
);
create unique index vocab_word_lemma_uq on vocab_word (lemma) where lemma is not null;
create index vocab_word_preparing_idx on vocab_word (updated_at) where status = 'PREPARING';

create table vocab_word_form (
    form    varchar(40) primary key,                                   -- normalised: one card per spelling
    word_id bigint      not null references vocab_word (id) on delete cascade
);
create index vocab_word_form_word_idx on vocab_word_form (word_id);

create table vocab_saved_word (
    id                 uuid        primary key,
    user_id            bigint      not null references app_user (id) on delete cascade,
    word_id            bigint      not null references vocab_word (id) on delete restrict,
    state              varchar(10) not null check (state in ('NEW', 'LEARNING', 'MASTERED')),
    box                smallint    check (box between 1 and 4),
    due_on             date,
    last_answered_on   date,
    source_exercise_id bigint      references exercise (id) on delete set null,
    source_sentence    varchar(400),
    added_on           date        not null,
    created_at         timestamptz not null default now(),
    unique (user_id, word_id),
    check (state = 'NEW' or box is not null)
);
create index vocab_saved_word_due_idx on vocab_saved_word (user_id, due_on) where state = 'LEARNING';
create index vocab_saved_word_word_idx on vocab_saved_word (word_id);

create table vocab_session (
    id          uuid        primary key,
    user_id     bigint      not null references app_user (id) on delete cascade,
    kind        varchar(8)  not null check (kind in ('LEARN', 'REVIEW')),
    content     jsonb       not null,                                  -- word snapshots, tasks with keys, queue
    retries     int         not null default 0 check (retries >= 0),
    started_at  timestamptz not null,
    finished_at timestamptz
);
create index vocab_session_cleanup_idx on vocab_session (started_at);

create table vocab_ai_usage (
    user_id bigint not null references app_user (id) on delete cascade,
    day     date   not null,                                           -- a day in the vocabulary day zone
    count   int    not null default 0 check (count >= 0),
    primary key (user_id, day)
);
