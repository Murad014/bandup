-- =============================================================================
-- V5 — let the application choose the ids of exercises, groups and questions.
-- The Content domain gives a new question its id before saving (taken from the
-- table's own sequence), so a question keeps the same id across edits and
-- attempt_answer rows never point at the wrong question after a reorder.
-- "by default" still fills the id from the same sequence when none is given;
-- no data changes.
-- =============================================================================

alter table exercise       alter column id set generated by default;
alter table question_group alter column id set generated by default;
alter table question       alter column id set generated by default;
